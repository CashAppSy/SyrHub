// Explicit public asset list: never publish credentials, tools or old APKs.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
// Plain JS exports support the older bundler used by hosted Pages builds.
let seedModule = '// Generated by build/site.js from data/*.json. Do not edit manually.\n';
for (const name of ['apps','categories','promotions','reviews']) {
  const data = JSON.parse(fs.readFileSync(path.join(root, 'data', name + '.json'), 'utf8'));
  seedModule += 'export const ' + name + ' = ' + JSON.stringify(data) + ';\n';
}
fs.writeFileSync(path.join(root, 'server', 'catalog-seed.mjs'), seedModule);
fs.writeFileSync(path.join(root,'server','page-template.mjs'),'// Generated by build/site.js from index.html. Do not edit manually.\nexport const template = '+JSON.stringify(fs.readFileSync(path.join(root,'index.html'),'utf8'))+';\n');
const out = path.join(root, 'dist');
fs.mkdirSync(out, {recursive:true});
for (const file of ['index.html','offline.html','sw.js','manifest.webmanifest','storage.js','apps-data.js','promotions-data.js','reviews-data.js','SyrHub-Icon.png','enhancements.css','contributions.js','account.js','local-data.js','_headers']) fs.copyFileSync(path.join(root,file),path.join(out,file));
const sitemapApps=JSON.parse(fs.readFileSync(path.join(root,'data','apps.json'),'utf8'));
fs.writeFileSync(path.join(out,'sitemap.xml'),'<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>https://syrhub.pages.dev/</loc></url>'+sitemapApps.filter(app=>!app.isDemo).map(app=>'<url><loc>https://syrhub.pages.dev/apps/'+encodeURIComponent(app.id)+'</loc></url>').join('')+'</urlset>');
fs.cpSync(path.join(root,'admin'),path.join(out,'admin'),{recursive:true});
fs.cpSync(path.join(root,'icons'),path.join(out,'icons'),{recursive:true});
console.log('Web/PWA assets prepared in dist/');
